#!/usr/bin/env node
/* ─────────────────────────────────────────────────────────────
   Writes public/_redirects from the CMS blog_redirects table.

   Netlify serves that file as real HTTP 301s, so renamed article
   URLs keep their link equity on the mirror. On the droplet (a
   plain `next start` behind nginx) the client-side resolver in
   DynamicBlogViewer handles the same table live, without a
   deploy — so a rename never produces a dead link on either host.

   Deliberately does NOT touch next.config.js: production keeps a
   local uncommitted edit to that file (output:'export' removed),
   and changing it upstream would break `git pull --ff-only`
   on the droplet.

   Run before a deploy:  node scripts/generate-blog-redirects.mjs
   ───────────────────────────────────────────────────────────── */

import { createClient } from '@supabase/supabase-js'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')

function loadEnv() {
  const out = { ...process.env }
  for (const f of ['.env.local', '.env']) {
    try {
      for (const line of readFileSync(resolve(ROOT, f), 'utf8').split(/\r?\n/)) {
        const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
        if (m && !out[m[1]]) out[m[1]] = m[2].replace(/^["']|["']$/g, '')
      }
    } catch { /* optional */ }
  }
  return out
}

const env = loadEnv()
const url = env.NEXT_PUBLIC_SUPABASE_URL
const key = env.SUPABASE_SERVICE_ROLE_KEY || env.NEXT_PUBLIC_SUPABASE_ANON_KEY

const HEADER = `# Generated by scripts/generate-blog-redirects.mjs — do not edit by hand.
# Article URL changes recorded by the CMS become real 301s here.
`

// Legacy subdomain routes that no longer exist as their own pages.
const STATIC_RULES = [
  '/insights            /blog/                 301',
  '/insights/*          /blog/                 301',
  '/reports             /blog/reports/         301',
  '/reports/*           /blog/reports/         301',
]

async function main() {
  const rules = [...STATIC_RULES]

  if (!url || !key) {
    console.warn('! Supabase env not set — writing static rules only.')
  } else {
    const sb = createClient(url, key, { auth: { persistSession: false } })
    const { data, error } = await sb
      .from('blog_redirects')
      .select('from_path, to_path, status_code, is_active')
      .eq('is_active', true)
    if (error) {
      console.warn(`! could not read blog_redirects (${error.message}) — writing static rules only.`)
    } else {
      for (const r of data || []) {
        if (!r.from_path || !r.to_path || r.from_path === r.to_path) continue
        rules.push(`${r.from_path.padEnd(20)} ${r.to_path.padEnd(22)} ${r.status_code || 301}`)
      }
      console.log(`✓ ${(data || []).length} CMS redirect(s) included`)
    }
  }

  const target = resolve(ROOT, 'public', '_redirects')
  writeFileSync(target, `${HEADER}\n${rules.join('\n')}\n`, 'utf8')
  console.log(`✓ wrote ${rules.length} rule(s) → public/_redirects`)
}

main().catch((e) => { console.error('✖', e.message); process.exit(1) })
